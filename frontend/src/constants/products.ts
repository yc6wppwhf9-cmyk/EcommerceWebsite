// ─── Helper Functions ────────────────────────────────────────
export function getProductById(id: string): Product | undefined {
  return PRODUCTS.find((p) => p.id.toLowerCase() === id.toLowerCase() || p.sku?.toLowerCase() === id.toLowerCase());
}

export function getProductBySlug(slug: string): Product | undefined {
  return PRODUCTS.find((p) => p.slug === slug);
}

export function getProductsByCategory(categorySlug: string): Product[] {
  return PRODUCTS.filter((p) => p.category === categorySlug || p.subcategory === categorySlug);
}

export function getPremiumProducts(): Product[] {
  return PRODUCTS.filter((p) => p.isPremium);
}

export function getCategoryBySlug(slug: string): CategoryInfo | undefined {
  return CATEGORIES.find((c) => c.slug === slug);
}

export function getSubcategories(parentSlug: string): CategoryInfo[] {
  return CATEGORIES.filter((c) => c.parentCategory === parentSlug);
}

export function getBestSellers(): Product[] {
  return PRODUCTS.filter((p) => p.isBestSeller).slice(0, 12);
}

export function getNewArrivals(): Product[] {
  return PRODUCTS.filter((p) => p.isNew).slice(0, 12);
}

export function searchProducts(query: string): Product[] {
  const q = query.toLowerCase();
  return PRODUCTS.filter(
    (p) =>
      p.name.toLowerCase().includes(q) ||
      p.category.toLowerCase().includes(q) ||
      (p.subcategory && p.subcategory.toLowerCase().includes(q)) ||
      (p.family && p.family.toLowerCase().includes(q)) ||
      (p.sku && p.sku.toLowerCase().includes(q)) ||
      (p.description && p.description.toLowerCase().includes(q))
  );
}

export function formatPrice(price: number): string {
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    minimumFractionDigits: 0,
    maximumFractionDigits: 0,
  }).format(price);
}

